#!/usr/bin/env python3
"""cloud_catalog.py - build / verify catalog.json for the URUSHI `verified` branch.

Layout on the `verified` branch:

    catalog.json                        <- generated by this tool
    community/<id>/manifest.json        <- written by the script author, reviewed by the maintainer
    community/<id>/init.lua             <- entry file (default; override with "entry")
    community/<id>/...                  <- other files (.lua .json .txt .png .hlsl .hlsli)
    (a package may be shader-only: no .lua at all; .hlsl/.hlsli files are installed to shaders/cloud/<id>/)

manifest.json:
    {
      "id": "drift_sound",              (a-z 0-9 _ - ; max 40)
      "name": "Drift Sound", "name_ru": "Звук дрифта",
      "author": "someone",
      "version": "1.0.0",
      "description": "...", "description_ru": "...",
      "min_urushi": "0.2.0",            (optional)
      "entry": "init.lua"               (optional)
    }

Usage (from the root of the `verified` branch checkout):
    python tools/cloud_catalog.py            # regenerate catalog.json
    python tools/cloud_catalog.py --check    # fail if catalog.json is out of date / invalid (use in CI)

The client re-validates everything (ids, paths, extensions, SHA-256), this tool just refuses to produce a bad catalog.
Pure Python stdlib.
"""
import argparse
import hashlib
import json
import os
import re
import sys

ID_RE = re.compile(r"^[a-z0-9_-]{1,40}$")
PART_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
ALLOWED_EXT = {".lua", ".json", ".txt", ".png", ".hlsl", ".hlsli"}
MAX_FILE = 512 * 1024
MAX_FILES = 32


def valid_rel(path):
    if not path or len(path) > 100:
        return False
    if os.path.splitext(path)[1].lower() not in ALLOWED_EXT:
        return False
    for part in path.split("/"):
        if part in ("", ".", "..") or part.startswith(".") or not PART_RE.match(part):
            return False
    return True


def build(root):
    community = os.path.join(root, "community")
    items, errors = [], []
    if not os.path.isdir(community):
        return items, ["no community/ folder"]
    for sid in sorted(os.listdir(community)):
        folder = os.path.join(community, sid)
        if not os.path.isdir(folder):
            continue
        mpath = os.path.join(folder, "manifest.json")
        if not os.path.isfile(mpath):
            errors.append(f"{sid}: manifest.json missing")
            continue
        try:
            with open(mpath, encoding="utf-8") as f:
                m = json.load(f)
        except Exception as e:  # noqa: BLE001
            errors.append(f"{sid}: manifest.json invalid ({e})")
            continue
        if m.get("id") != sid or not ID_RE.match(sid):
            errors.append(f"{sid}: manifest id must equal the folder name and match {ID_RE.pattern}")
            continue
        if not m.get("version"):
            errors.append(f"{sid}: version missing")
            continue
        entry = m.get("entry", "")
        files = []
        for dirpath, _dirs, names in os.walk(folder):
            for name in sorted(names):
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, folder).replace(os.sep, "/")
                if rel == "manifest.json":
                    continue
                if not valid_rel(rel):
                    errors.append(f"{sid}: file not allowed: {rel}")
                    continue
                data = open(full, "rb").read()
                if len(data) > MAX_FILE:
                    errors.append(f"{sid}: {rel} is larger than {MAX_FILE // 1024} KB")
                    continue
                files.append({"path": rel, "sha256": hashlib.sha256(data).hexdigest()})
        if len(files) > MAX_FILES:
            errors.append(f"{sid}: more than {MAX_FILES} files")
            continue
        paths = [f["path"] for f in files]
        has_lua = any(p.endswith(".lua") for p in paths)
        if not entry:
            entry = "init.lua" if has_lua else ""   # shader-only packs have no entry
        if entry and entry not in paths:
            errors.append(f"{sid}: entry file '{entry}' not found")
            continue
        if not has_lua and not any(p.lower().endswith((".hlsl", ".hlsli")) for p in paths):
            errors.append(f"{sid}: package has neither Lua nor shader files")
            continue
        item = {k: m[k] for k in ("id", "name", "name_ru", "author", "version", "description", "description_ru", "min_urushi") if k in m}
        item.setdefault("name", sid)
        if entry and entry != "init.lua":
            item["entry"] = entry
        item["files"] = sorted(files, key=lambda f: f["path"])
        items.append(item)
    return items, errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify only; exit 1 if catalog.json is stale or invalid")
    ap.add_argument("--root", default=".", help="root of the verified-branch checkout")
    args = ap.parse_args()

    items, errors = build(args.root)
    for e in errors:
        print("ERROR:", e, file=sys.stderr)
    if errors:
        return 1

    text = json.dumps({"version": 1, "scripts": items}, indent=2, ensure_ascii=False) + "\n"
    path = os.path.join(args.root, "catalog.json")
    if args.check:
        current = open(path, encoding="utf-8").read() if os.path.isfile(path) else ""
        if current != text:
            print("catalog.json is out of date - run tools/cloud_catalog.py", file=sys.stderr)
            return 1
        print(f"catalog.json OK ({len(items)} scripts)")
        return 0
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote catalog.json ({len(items)} scripts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
